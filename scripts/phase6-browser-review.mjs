import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const runtime=JSON.parse(fs.readFileSync('.local/runtime.json','utf8').replace(/^\uFEFF/,''));
const url='http://127.0.0.1:'+runtime.web_port;
const browser=await chromium.launch({channel:'chromium'});
const errors=[];
try{
  const context=await browser.newContext({baseURL:url,viewport:{width:1440,height:1000}}),page=await context.newPage();
  page.on('pageerror',error=>errors.push({type:'page',name:error.name}));
  page.on('console',message=>{if(message.type()==='error')errors.push({type:'console'});});
  page.on('response',response=>{if(response.status()>=400)errors.push({type:'http',status:response.status(),path:new URL(response.url()).pathname});});
  await page.goto('/dev');await page.getByRole('checkbox',{name:'Show fictional scenario controls (developer)',exact:true}).check();await page.getByRole('button',{name:'Continue as Maria'}).click();
  const base='/api/encounters/10000000-0000-4000-8000-000000000001';
  await expect(page.getByText('Follow-up with Dr. Chen',{exact:true})).toBeVisible({timeout:60000});
  const before=await (await context.request.get(base)).json();
  await page.goto('/visit');const office=page.getByRole('region',{name:'Office follow-through',exact:true});
  await expect(office).toBeVisible({timeout:60000});
  await expect(page.getByRole('region',{name:'Visit conversation',exact:true})).toBeVisible({timeout:60000});
  await expect(page.getByRole('region',{name:'Vene participation',exact:true})).toBeVisible({timeout:60000});
  const status=await (await context.request.get(base+'/execution')).json();expect(status.configured).toBe(true);
  await office.getByText('Development sandbox · change office conditions',{exact:true}).click();
  await page.evaluate(()=>{if(document.activeElement instanceof HTMLElement)document.activeElement.blur();window.scrollTo(0,0);});
  await page.screenshot({path:'docs/qa/phase-06-preview-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>{if(document.activeElement instanceof HTMLElement)document.activeElement.blur();window.scrollTo(0,0);});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  await page.screenshot({path:'docs/qa/phase-06-preview-mobile.png',fullPage:true});
  await office.scrollIntoViewIfNeeded();
  await page.screenshot({path:'docs/qa/phase-06-preview-mobile-viewport.png'});
  const skipLink=await page.locator('.skip-link').evaluate(element=>({focused:element===document.activeElement,top:element.getBoundingClientRect().top}));
  await page.goto('/follow-up');await expect(page.getByRole('region',{name:'Office follow-through',exact:true})).toBeVisible();
  const after=await (await context.request.get(base)).json();expect(after).toEqual(before);
  fs.writeFileSync('docs/qa/phase-06-preview-review.json',JSON.stringify({checked_at:new Date().toISOString(),url,launcher:'used in actual browser',office_panel:true,sandbox_configured:status.configured,saved_visit_preserved:JSON.stringify(after)===JSON.stringify(before),mobile_overflow:overflow,skip_link:skipLink,errors,actions_created:false,room_joined:false,provider_calls:false},null,2)+'\n');
  if(errors.length||overflow)throw new Error('Preview review found browser errors or overflow.');
  console.log('Phase 6 preview inspected on desktop/mobile and follow-up; saved visit preserved.');
}finally{await browser.close();}
