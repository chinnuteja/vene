import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import {base,launch} from './helpers';
import {ownedProcess} from './process-control';
const follow=base+'/continuity';
async function state(context){return (await context.request.get(follow)).json();}

test('continuity recovery keeps signed replies, document differences and scoped family delivery honest',async({browser})=>{
  test.setTimeout(180000);
  const patient=await browser.newContext(),doctor=await browser.newContext(),family=await browser.newContext();
  const p=await patient.newPage(),d=await doctor.newPage(),f=await family.newPage();
  const errors:string[]=[];for(const page of [p,d,f])page.on('pageerror',e=>errors.push(e.name));
  let nextContext;
  try{
    await launch(patient);await launch(doctor,'clinician');await launch(family,'family');
    await Promise.all([p.goto('/follow-up'),d.goto('/follow-up'),f.goto('/follow-up')]);
    const region=p.getByRole('region',{name:'After-visit continuity',exact:true});await expect(region).toBeVisible();
    const beforeOffice=(await (await patient.request.get(base+'/execution')).json()).actions;
    const beforeCount=(await state(patient)).callback_count;
    await region.getByText('Development sandbox · office replies',{exact:true}).click();
    await region.getByRole('button',{name:'Repeat the sandbox office reply',exact:true}).click();
    await expect.poll(async()=>(await state(patient)).callback_count,{timeout:20000}).toBeGreaterThan(beforeCount);
    expect((await (await patient.request.get(base+'/execution')).json()).actions.map(a=>a.id)).toEqual(beforeOffice.map(a=>a.id));
    const planBefore=(await (await patient.request.get(base)).json()).plan;
    await region.getByLabel('After-visit PDF',{exact:true}).setInputFiles(path.resolve('fixtures/documents/after-visit-conflict.pdf'));
    await region.getByRole('button',{name:'Compare the document',exact:true}).click();
    const doc=p.getByRole('article',{name:'Document: After-visit instructions',exact:true});await expect(doc).toBeVisible();
    await expect(doc.getByText('Differences remain unresolved',{exact:true})).toBeVisible();
    const uploaded=(await state(patient)).documents[0];expect(uploaded.format).toBe('pdf');expect(uploaded.pages.length).toBe(1);
    expect(uploaded.differences.map(x=>x.kind)).toContain('clinical_instruction');
    expect((await state(doctor)).documents).toEqual([]);
    const share=doc.getByRole('group',{name:'Share document: After-visit instructions with'});
    await share.getByRole('checkbox',{name:'Dr. Chen',exact:true}).click();
    const dDoc=d.getByRole('article',{name:'Document: After-visit instructions',exact:true});await expect(dDoc).toBeVisible();
    await dDoc.getByLabel('Review note for After-visit instructions',{exact:true}).fill('Discuss the differences. No medication change is authorized.');
    await dDoc.getByRole('button',{name:'Record clinician review',exact:true}).click();
    await expect(doc.getByText('Reviewed by clinician',{exact:true})).toBeVisible();
    expect((await (await patient.request.get(base)).json()).plan).toEqual(planBefore);
    await region.getByRole('button',{name:'Prepare the update',exact:true}).click();
    const draft=region.getByRole('article',{name:'Family update',exact:true}).first();
    await expect(draft.getByText('Draft · not sent',{exact:true})).toBeVisible();
    expect((await state(family)).family_updates).toEqual([]);
    await draft.getByRole('button',{name:'Approve this family update',exact:true}).click();
    await expect.poll(async()=>(await state(patient)).family_updates[0]?.state,{timeout:45000}).toBe('delivered');
    const delivered=(await state(patient)).family_updates[0];
    await expect(f.getByRole('article',{name:'Family update',exact:true})).toContainText('Sandbox delivery acknowledged');
    expect(delivered.text).not.toContain('PRIVATE_CANARY');expect(delivered.text).not.toContain('Who:');
    const savedVisit=await (await patient.request.get(base)).json();
    await ownedProcess('stop','execution');await ownedProcess('stop','api');
    await ownedProcess('restart','api');await ownedProcess('restart','execution');
    await Promise.all([p.reload(),d.reload(),f.reload()]);
    await expect(p.getByRole('article',{name:'Document: After-visit instructions',exact:true})).toContainText('Reviewed by clinician');
    expect((await (await patient.request.get(base)).json()).plan).toEqual(savedVisit.plan);
    expect((await state(family)).family_updates[0].receipt.receipt_id).toBe(delivered.receipt.receipt_id);
    await p.evaluate(()=>{if(document.activeElement instanceof HTMLElement)document.activeElement.blur();window.scrollTo(0,0);});
    await p.screenshot({path:'docs/qa/phase-07-continuity-desktop.png',fullPage:true});
    await p.setViewportSize({width:390,height:844});await p.evaluate(()=>window.scrollTo(0,0));
    expect(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await p.screenshot({path:'docs/qa/phase-07-continuity-mobile.png',fullPage:true});
    await p.getByRole('article',{name:'Document: After-visit instructions',exact:true}).screenshot({path:'docs/qa/phase-07-document-mobile.png'});
    await p.getByRole('article',{name:'Family update',exact:true}).first().screenshot({path:'docs/qa/phase-07-family-mobile.png'});
    const nextResponse=p.waitForResponse(r=>r.url().endsWith('/continuity/next-visit')&&r.request().method()==='POST');
    await p.getByRole('button',{name:'Create private next-visit preparation',exact:true}).click();
    const created=await (await nextResponse).json();expect(created.encounter_id).toBeTruthy();
    nextContext=await browser.newContext();
    const redeemed=await nextContext.request.post('/api/auth/redeem',{headers:{'x-vene-intent':'mutation'},data:{token:created.invitation.token}});expect(redeemed.status()).toBe(200);
    const n=await nextContext.newPage();await n.goto('/prepare');await expect(n.getByText('Preparing for your next visit',{exact:true})).toBeVisible();
    const nextBase='/api/encounters/'+created.encounter_id;const fresh=await (await nextContext.request.get(nextBase)).json();
    expect(fresh.preparation_approved).toBe(false);expect(fresh.priorities.every(q=>q.audiences.length===0&&!q.approved)).toBe(true);
    expect((await family.request.get(nextBase)).status()).toBe(404);
    await n.goto('/follow-up');await n.getByText('Delete this local visit',{exact:true}).click();
    await n.getByLabel('Deletion confirmation',{exact:true}).fill('DELETE SYNTHETIC VISIT');
    await n.getByRole('button',{name:'Delete this local visit and its private preparations',exact:true}).click();
    await expect(n.getByRole('heading',{name:'Your visit, by invitation.',exact:true})).toBeVisible();
    expect((await nextContext.request.get(nextBase)).status()).toBe(401);
    expect((await patient.request.get(base)).status()).toBe(200);
    expect(errors).toEqual([]);
    fs.writeFileSync('docs/qa/phase-07-browser-evidence.json',JSON.stringify({checked_at:new Date().toISOString(),actual_http_callbacks:true,duplicate_reply_created_no_action:true,document:'original machine-readable PDF',clinical_state_unchanged:true,family_payload_selected_fields:true,delivery_receipt:delivered.receipt.receipt_id,api_and_worker_restarted:true,saved_plan_and_receipt_preserved:true,new_visit_private:true,disposable_visit_deleted:true,original_visit_retained:true,mobile_overflow:false,errors},null,2)+'\n');
  }finally{await nextContext?.close();await Promise.all([patient.close(),doctor.close(),family.close()]);}
});
